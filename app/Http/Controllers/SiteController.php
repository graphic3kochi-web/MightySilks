<?php

namespace App\Http\Controllers;

use App\Models\Blog;
use App\Models\Collection;
use App\Models\JobOpening;
use App\Models\Product;
use App\Models\Setting;
use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Request;
use Illuminate\Http\Response;

/**
 * The storefront: each page at a clean URL (/about…; the old about.html redirects), rendered
 * from resources/views/pages; shop pages list their collection's products from the database.
 */
class SiteController extends Controller
{
    public function page(string $page = 'index')
    {
        abort_unless(view()->exists("pages.$page"), 404);

        // /search?q=…: the matching products in the shop grid.
        if ($page === 'search') {
            $q = trim((string) request('q'));
            $products = $q === '' ? collect() : Product::active()->search($q)->orderBy('position')->get();

            return view('pages.search', compact('products', 'q'));
        }

        $collection = Collection::where('slug', $page)->first();
        $products = $collection ? $collection->products()->where('is_active', true)->get() : collect();

        return view("pages.$page", compact('products'));
    }

    /** about.html → /about (index.html → /), keeping the query string: old links, bookmarks and emails. */
    public function legacy(Request $request, string $page): RedirectResponse
    {
        $query = $request->getQueryString();

        return redirect(($page === 'index' ? '/' : "/$page").($query ? "?$query" : ''), 301);
    }

    /** api/search?q=…: the header search's suggestions, the first few matches and how many there are. */
    public function suggest(Request $request): array
    {
        $q = trim((string) $request->query('q'));
        if (mb_strlen($q) < 2) {
            return ['total' => 0, 'products' => []];
        }
        $matches = Product::active()->search($q)->orderBy('position');

        return [
            'total' => (clone $matches)->count(),
            'products' => $matches->limit(6)->get()->map(fn (Product $p) => [
                'code' => $p->code,
                'title' => $p->title,
                'category' => $p->categoryLabel(),
                'price' => inr($p->price),
                'image' => $p->image(),
            ])->all(),
        ];
    }

    /** js/products.js: the catalogue the product page, cart and checkout read. */
    public function productsScript(): Response
    {
        $products = Product::active()->orderBy('position')->get()->mapWithKeys(fn (Product $p) => [$p->code => $p->toCatalogue()]);

        return $this->script('window.PRODUCTS = '.$this->json($products).';');
    }

    /** js/blogs.js: published posts, newest first. */
    public function blogsScript(): Response
    {
        $posts = Blog::where('is_published', true)->orderByDesc('published_on')->get()->mapWithKeys(fn (Blog $b) => [$b->slug => $b->toScript()]);

        return $this->script('window.BLOGS = '.$this->json($posts).';');
    }

    /** js/jobs.js: open roles and the benefits every role offers. */
    public function jobsScript(): Response
    {
        $jobs = JobOpening::where('is_open', true)->orderBy('position')->get()->mapWithKeys(fn (JobOpening $j) => [$j->slug => $j->toScript()]);
        $offer = array_values(array_filter(array_map('trim', explode("\n", (string) Setting::get('job_offer')))));

        return $this->script('window.JOB_OFFER = '.$this->json($offer).";\n\nwindow.JOBS = ".$this->json($jobs).';');
    }

    private function json(mixed $data): string
    {
        return json_encode($data ?: new \stdClass, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_HEX_TAG);
    }

    private function script(string $body): Response
    {
        return response("// Generated by the store from its database.\n$body\n", 200, [
            'Content-Type' => 'text/javascript; charset=utf-8',
            'Cache-Control' => 'no-cache',
        ]);
    }
}
